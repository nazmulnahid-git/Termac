const FOLDER_COLOR = '#8f99a8';

const draw = (Icon, color, size) => <Icon className="ftype" size={size} strokeWidth={1.75} style={{ color }} aria-hidden="true" />;

export function FileIcon({ name, size = 16 }) {
  const lower = name.toLowerCase();
  const hit = BY_NAME[lower] || (lower.startsWith('.env') && BY_EXT.env) || (/^(vite|webpack|rollup|eslint|babel|jest|vitest|tailwind|postcss)\.config\./.test(lower) && [FileCog, C.config]) || BY_EXT[ext(lower)];
  return hit ? draw(hit[0], hit[1], size) : draw(File, C.plain, size);
}

export function FolderIcon({ name, open, root, size = 16 }) {
  if (root) return draw(FolderRoot, '#4c8fd6', size);
  const hit = FOLDERS[name.toLowerCase()];
  if (hit) return draw(hit[0], hit[1], size);
  return draw(open ? FolderOpen : Folder, FOLDER_COLOR, size);
}
